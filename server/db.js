/** Cria as tabelas e os dados mínimos (gestor, disciplinas, configuração). */
export async function iniciarBanco() {
  await pool.query(SCHEMA);
  for (const [k, v] of Object.entries(CONFIG_PADRAO)) {
    await query('INSERT INTO config (chave, valor) VALUES (?, ?) ON CONFLICT (chave) DO NOTHING', [k, v]);
  }
  await query('INSERT INTO sistema (chave, valor) VALUES (?, ?) ON CONFLICT (chave) DO NOTHING', ['jwt_secret', crypto.randomBytes(48).toString('hex')]);
  if (!(await db.get("SELECT 1 FROM usuarios WHERE papel = 'gestor'"))) {
    await db.run("INSERT INTO usuarios (nome, email, senha_hash, papel) VALUES (?, ?, ?, 'gestor')",
      'Administrador', 'admin@escola.com', bcrypt.hashSync('admin123', 10));
    console.log('Usuario gestor criado: admin@escola.com / admin123 (troque a senha!)');
  }
  if (!(await db.get('SELECT 1 FROM disciplinas'))) {
    const nomes = ['Língua Portuguesa', 'Matemática', 'Ciências', 'História', 'Geografia', 'Arte', 'Educação Física', 'Língua Inglesa'];
    for (const [i, n] of nomes.entries()) {
      await db.run('INSERT INTO disciplinas (nome, carga_horaria, ordem) VALUES (?, ?, ?)', n, i < 2 ? 200 : 80, i + 1);
    }
  }
}

let cacheConfig = null;
export async function getConfig() {
  if (!cacheConfig) {
    const cfg = {};
    for (const r of await db.all('SELECT chave, valor FROM config')) cfg[r.chave] = r.valor;
    cacheConfig = cfg;
  }
  return { ...cacheConfig };
}
export function limparCacheConfig() { cacheConfig = null; }

export async function segredo(chave) {
  return (await db.get('SELECT valor FROM sistema WHERE chave = ?', chave))?.valor;
}

export async function fecharBanco() { await pool.end(); }
